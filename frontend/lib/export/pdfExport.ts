/**
 * PDF Export Utilities for Admin Reports
 * Client-side PDF generation using HTML/Canvas approach
 */

/**
 * Generate simple HTML table and trigger print to PDF
 */
export function generatePdfFromTable(
  tableHtml: string,
  title: string,
  filename: string
): void {
  const printWindow = window.open('', '', 'height=600,width=800');
  
  if (!printWindow) {
    alert('Please disable popup blockers to export PDF');
    return;
  }

  const html = `
    <!DOCTYPE html>
    <html>
      <head>
        <title>${title}</title>
        <style>
          body {
            font-family: Arial, sans-serif;
            margin: 20px;
            background: white;
            color: #333;
          }
          h1 {
            text-align: center;
            color: #333;
            margin-bottom: 20px;
            font-size: 24px;
          }
          .metadata {
            text-align: right;
            font-size: 12px;
            color: #666;
            margin-bottom: 20px;
          }
          table {
            width: 100%;
            border-collapse: collapse;
            margin-top: 20px;
          }
          th {
            background-color: #f0f0f0;
            padding: 12px;
            text-align: left;
            border: 1px solid #ddd;
            font-weight: bold;
            font-size: 13px;
          }
          td {
            padding: 10px;
            border: 1px solid #ddd;
            font-size: 12px;
          }
          tr:nth-child(even) {
            background-color: #f9f9f9;
          }
          .footer {
            margin-top: 30px;
            text-align: center;
            font-size: 11px;
            color: #999;
            border-top: 1px solid #ddd;
            padding-top: 10px;
          }
          @media print {
            body {
              margin: 0;
              padding: 10mm;
            }
            .no-print {
              display: none;
            }
          }
        </style>
      </head>
      <body>
        <h1>${title}</h1>
        <div class="metadata">
          Generated on: ${new Date().toLocaleString()}
        </div>
        ${tableHtml}
        <div class="footer">
          <p>This report was automatically generated by InheritX Admin Dashboard</p>
        </div>
        <div class="no-print" style="margin-top: 20px; text-align: center;">
          <button onclick="window.print();" style="padding: 10px 20px; background: #333; color: white; border: none; border-radius: 4px; cursor: pointer;">
            Print / Save as PDF
          </button>
          <button onclick="window.close();" style="padding: 10px 20px; background: #666; color: white; border: none; border-radius: 4px; cursor: pointer; margin-left: 10px;">
            Close
          </button>
        </div>
      </body>
    </html>
  `;

  printWindow.document.write(html);
  printWindow.document.close();
}

/**
 * Export payouts table as PDF
 */
export function exportPayoutsAsPdf(payouts: any[], title = 'Payout Settlements Report'): void {
  let tableHtml = '<table>';
  
  // Headers
  tableHtml += `
    <thead>
      <tr>
        <th>Payout ID</th>
        <th>Plan ID</th>
        <th>Beneficiary</th>
        <th>Amount</th>
        <th>Currency</th>
        <th>Anchor Partner</th>
        <th>Status</th>
        <th>Settlement Date</th>
      </tr>
    </thead>
  `;

  // Rows
  tableHtml += '<tbody>';
  for (const payout of payouts) {
    tableHtml += `
      <tr>
        <td>${escapeHtml(payout.id)}</td>
        <td>${escapeHtml(payout.planId)}</td>
        <td>${escapeHtml(payout.beneficiary)}</td>
        <td>${payout.amount.toLocaleString()}</td>
        <td>${escapeHtml(payout.currency)}</td>
        <td>${escapeHtml(payout.anchor)}</td>
        <td>${escapeHtml(payout.status)}</td>
        <td>${new Date(payout.date).toLocaleDateString()}</td>
      </tr>
    `;
  }
  tableHtml += '</tbody></table>';

  generatePdfFromTable(tableHtml, title, 'payouts-report.pdf');
}

/**
 * Export users table as PDF
 */
export function exportUsersAsPdf(users: any[], title = 'Users Report'): void {
  let tableHtml = '<table>';
  
  // Headers
  tableHtml += `
    <thead>
      <tr>
        <th>Wallet Address</th>
        <th>KYC Status</th>
        <th>Active Plans</th>
        <th>Total Plans</th>
        <th>Status</th>
        <th>Join Date</th>
        <th>Last Active</th>
      </tr>
    </thead>
  `;

  // Rows
  tableHtml += '<tbody>';
  for (const user of users) {
    tableHtml += `
      <tr>
        <td>${escapeHtml(user.walletAddress)}</td>
        <td>${escapeHtml(user.kycStatus)}</td>
        <td>${user.activePlansCount}</td>
        <td>${user.totalPlansCount || user.activePlansCount}</td>
        <td>${escapeHtml(user.status)}</td>
        <td>${new Date(user.joinDate).toLocaleDateString()}</td>
        <td>${new Date(user.lastActive).toLocaleDateString()}</td>
      </tr>
    `;
  }
  tableHtml += '</tbody></table>';

  generatePdfFromTable(tableHtml, title, 'users-report.pdf');
}

/**
 * Escape HTML special characters
 */
function escapeHtml(text: string): string {
  const map: Record<string, string> = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#039;',
  };
  return text.replace(/[&<>"']/g, char => map[char]);
}
